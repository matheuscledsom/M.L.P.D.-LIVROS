function cleanPublisherKey(value) {
  return String(value || '')
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/\b(ltda|s\.?a\.?|s\/a|eireli|me|epp)\b/gi, ' ')
    .replace(/[^\p{L}\p{N}&]+/gu, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

const PUBLISHER_LOOKUP = new Map();
for (const entry of BRAZILIAN_PUBLISHERS) {
  PUBLISHER_LOOKUP.set(cleanPublisherKey(entry.name), entry.name);
  for (const alias of entry.aliases || []) {
    PUBLISHER_LOOKUP.set(cleanPublisherKey(alias), entry.name);
  }
}

export function normalizePublisherName(rawValue) {
  const trimmed = String(rawValue || '').trim();
  if (!trimmed) return '';

  const exactKey = cleanPublisherKey(trimmed);
  if (PUBLISHER_LOOKUP.has(exactKey)) {
    return PUBLISHER_LOOKUP.get(exactKey);
  }

  // Tentativa secundária removendo prefixos genéricos como "Editora " ou "Grupo "
  const withoutPrefix = exactKey
    .replace(/^(editora|edicoes|ed\.|grupo editorial|grupo)\s+/i, '')
    .trim();
  if (withoutPrefix && PUBLISHER_LOOKUP.has(withoutPrefix)) {
    return PUBLISHER_LOOKUP.get(withoutPrefix);
  }

  return trimmed.replace(/\s+/g, ' ');
}

export function searchBrazilianPublishers(
  query = '',
  { category = 'all', limit = 10 } = {}
) {
  const normQuery = cleanPublisherKey(query);
  const filteredByCategory =
    category === 'all'
      ? BRAZILIAN_PUBLISHERS
      : BRAZILIAN_PUBLISHERS.filter((p) => {
          if (category === 'literatura') return p.category === 'Literatura & Clássicos';
          if (category === 'hq') return p.category === 'Mangás & HQs';
          if (category === 'academico') return p.category === 'Técnico & Acadêmico';
          return true;
        });

  if (!normQuery) {
    return filteredByCategory.slice(0, limit);
  }

  const scored = [];
  for (const entry of filteredByCategory) {
    const nameKey = cleanPublisherKey(entry.name);
    const aliasHit = (entry.aliases || []).some((a) =>
      cleanPublisherKey(a).includes(normQuery)
    );
    let score = 0;
    if (nameKey === normQuery) score = 100;
    else if (nameKey.startsWith(normQuery)) score = 70;
    else if (nameKey.includes(normQuery)) score = 40;
    else if (aliasHit) score = 30;

    if (score > 0) {
      scored.push({ entry, score });
    }
  }

  return scored
    .sort((a, b) => b.score - a.score || a.entry.name.localeCompare(b.entry.name, 'pt-BR'))
    .slice(0, limit)
    .map((s) => s.entry);
}
